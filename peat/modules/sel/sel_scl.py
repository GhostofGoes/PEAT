"""
IEC 61850 Configured IED Description (CID) files and the IEC 61850 values
reported by SEL relays.

SEL relays with the IEC 61850 option store their IEC 61850 configuration in
``SET_61850.CID``, a Substation Configuration Language (SCL) XML file
(IEC 61850-6) generated by ACSELERATOR Architect and stored compressed with
zlib. The ``ID`` command reports the IED name, type, and configuration
version of the CID file the relay is using (SEL-351S Instruction Manual,
Appendix P, "IEC 61850 Configuration").

This module has no device or file I/O, so it works on data from FTP, YMODEM,
files being parsed, or tests:

- :func:`decompress_cid`: decompress a CID file (any zlib header, data after
  the end of the compressed stream is ignored, uncompressed XML is accepted),
  with a limit on the decompressed size.
- :func:`parse_scl`: parse the SCL into a :class:`dict` (header, IEDs, access
  points, logical devices, control blocks, and communication addresses).
- :func:`process_scl_into_dev`: put the parsed SCL into the device data model.
- :func:`process_id_info`: put the IEC 61850 values from the ``ID`` command
  into the device data model.

The values are stored in ``dev.extra["iec61850"]``:

- ``ied_name``, ``ied_type``, ``config_version``: as reported by the ``ID``
  command, or from the SCL if the ``ID`` command wasn't run.
- ``lib61850_id``: ``LIB61850ID`` from the ``ID`` command.
- ``manufacturer``: from the SCL.
- ``parse_failure``: the ``ID`` keys the relay reported as ``PARSE FAILURE``
  (the relay couldn't load its CID file).
- ``id_command``: the values reported by the ``ID`` command.
- ``scl``: summary of the SCL file (refer to :func:`process_scl_into_dev`).
- ``other_scl_files``: summaries of other SCL files for the same device.
- ``mismatches``: values that differ between the ``ID`` command and the SCL.

.. warning::
   CID files come from devices and aren't trusted. The decompressed size is
   limited (:data:`MAX_CID_SIZE`), and XML with a document type declaration
   (``<!DOCTYPE``, which is needed to declare entities) is rejected before
   it's parsed, so entity expansion ("billion laughs") and external entities
   can't be used. SCL files never need a DTD.
"""

import codecs
import re
import xml.etree.ElementTree as ET
import zlib
from dataclasses import dataclass
from typing import Any, BinaryIO, Final

from peat import DeviceData, Service, log
from peat.data.validators import validate_ip, validate_mac
from peat.protocols import clean_mac

#: XML namespace of SCL files (all editions of IEC 61850-6)
SCL_NAMESPACE: Final = "http://www.iec.ch/61850/2003/SCL"

#: Maximum size of the decompressed contents of a CID file (64 MiB). CID files
#: from relays are much smaller, so larger data is probably a decompression bomb.
MAX_CID_SIZE: Final = 64 * 1024 * 1024

#: Maximum amount of data decompressed when checking if a file is a CID
#: file (:func:`read_zlib_prefix`), since the check runs on every file
#: when parsing a directory (16 MiB)
MAX_CID_CHECK_SIZE: Final = 16 * 1024 * 1024

#: TCP port of IEC 61850 MMS (ISO transport over TCP, IEC 61850-8-1)
MMS_PORT: Final = 102

#: Key in ``dev.extra`` with the IEC 61850 values
EXTRA_KEY: Final = "iec61850"

#: Value in ``ID`` output when the relay couldn't load its CID file
PARSE_FAILURE: Final = "PARSE FAILURE"

#: Keys in the ``ID`` command output with IEC 61850 values, and the keys
#: used for them in ``dev.extra["iec61850"]``
ID_KEYS: Final = {
    "iedName": "ied_name",
    "type": "ied_type",
    "configVersion": "config_version",
    "LIB61850ID": "lib61850_id",
}

#: Values compared between the ``ID`` command and the IED in the SCL
#: (key in ``dev.extra["iec61850"]``, key in the IED dict from :func:`parse_scl`)
_COMPARED: Final = (
    ("ied_name", "name"),
    ("ied_type", "type"),
    ("config_version", "config_version"),
)

#: Size of the pieces of compressed data that are decompressed at a time
_CHUNK_SIZE: Final = 64 * 1024

#: Byte order marks, and the encoding to use for the data after them
_BOMS: Final = (
    (codecs.BOM_UTF8, "utf-8"),
    (codecs.BOM_UTF16_LE, "utf-16-le"),
    (codecs.BOM_UTF16_BE, "utf-16-be"),
)

#: Encoding in the XML declaration, e.g. ``<?xml version="1.0" encoding="UTF-8"?>``
_XML_ENCODING_RE: Final = re.compile(
    rb"""\s*<\?xml[^>]*?\sencoding\s*=\s*["']([A-Za-z][\w.\-]*)["']"""
)

#: A document type or entity declaration
_DTD_RE: Final = re.compile(r"<!\s*(?:DOCTYPE|ENTITY)\b", re.IGNORECASE)

#: Multiplier of a duration in seconds to milliseconds (``MinTime``, ``MaxTime``)
_MS_MULTIPLIERS: Final = {"": 1000.0, "m": 1.0, "u": 0.001, "\u00b5": 0.001}


@dataclass(frozen=True)
class CidContent:
    """
    Contents of a CID file, from :func:`decompress_cid`.
    """

    #: The decompressed data (or the data, if it wasn't compressed)
    data: bytes

    #: If the file was zlib-compressed
    compressed: bool

    #: The zlib header (the first two bytes) in hex, e.g. ``"7801"``
    zlib_header: str = ""

    #: Number of bytes after the end of the compressed data (ignored)
    trailing_bytes: int = 0

    #: If all of the compressed data was decompressed and its checksum is
    #: correct. :obj:`False` if the file is truncated or corrupted, and
    #: :attr:`data` is what could be decompressed.
    complete: bool = True

    #: Why the data couldn't be completely decompressed
    error: str = ""


def is_zlib_header(data: bytes) -> bool:
    """
    If data starts with a valid zlib header (RFC 1950): the DEFLATE
    compression method, a window size of at most 32 KiB, a correct check
    value, and no preset dictionary. All compression levels are accepted,
    e.g. ``7801`` (the header of SEL CID files), ``785E``, ``789C``, and ``78DA``.
    """
    if len(data) < 2:
        return False

    cmf, flg = data[0], data[1]

    return (
        cmf & 0x0F == 8  # DEFLATE
        and cmf >> 4 <= 7  # Window size
        and ((cmf << 8) | flg) % 31 == 0  # Check bits
        and not flg & 0x20  # Preset dictionary, unsupported
    )


def _strip_bom(data: bytes) -> tuple[bytes, str]:
    for bom, encoding in _BOMS:
        if data.startswith(bom):
            return data[len(bom) :], encoding
    return data, ""


def looks_like_xml(data: bytes | str) -> bool:
    """
    If data looks like XML: the first character (after a byte
    order mark and whitespace) is ``<``. This doesn't check if it's valid.
    """
    if isinstance(data, (bytes, bytearray, memoryview)):
        head, encoding = _strip_bom(bytes(data[:1024]))
        data = head.decode(encoding or "latin-1", errors="ignore")

    return data.lstrip("\ufeff").lstrip().startswith("<")


def decode_xml(data: bytes) -> str:
    """
    Decode XML data to text, using the byte order mark if there is one,
    then the encoding in the XML declaration, then UTF-8. If the data
    isn't valid in any of those, it's decoded as Latin-1, so this never fails.
    The byte order mark isn't included in the text.
    """
    data, bom_encoding = _strip_bom(bytes(data))
    if not bom_encoding and data[:2] in (b"<\x00", b"\x00<"):
        bom_encoding = "utf-16-le" if data[:1] == b"<" else "utf-16-be"
    if bom_encoding:
        return data.decode(bom_encoding, errors="replace")

    encodings = ["utf-8"]
    declared = _XML_ENCODING_RE.match(data)
    if declared:
        # The declaration was read as ASCII, so a UTF-16 or
        # UTF-32 encoding in it is wrong and is ignored.
        try:
            name = codecs.lookup(declared.group(1).decode("ascii")).name
        except LookupError:
            name = ""
        if name and not name.startswith(("utf-16", "utf-32")):
            encodings.insert(0, name)

    for encoding in encodings:
        try:
            return data.decode(encoding)
        except (LookupError, UnicodeDecodeError):
            continue

    return data.decode("latin-1")


def _encode_xml_text(text: str) -> bytes:
    """
    Encode XML text as UTF-8, so :func:`decode_xml` returns the same text.
    If the XML declaration names another encoding (e.g. ``ISO-8859-1``), a
    UTF-8 byte order mark is added, since :func:`decode_xml` uses the byte
    order mark before the declaration.
    """
    data = text.encode("utf-8")

    declared = _XML_ENCODING_RE.match(data)
    if declared:
        try:
            name = codecs.lookup(declared.group(1).decode("ascii")).name
        except LookupError:
            name = ""
        if name != "utf-8":
            return codecs.BOM_UTF8 + data

    return data


def decompress_cid(data: bytes | str, limit: int | None = None) -> CidContent:
    """
    Decompress the contents of a CID file.

    - Data with a zlib header (any compression level, refer to
      :func:`is_zlib_header`) is decompressed. Data after the end of the
      compressed stream (e.g. padding) is ignored.
    - Data that isn't compressed, but looks like XML, is returned as-is.
    - If the compressed data is truncated or corrupted, or its checksum
      (Adler-32) is wrong, the data that could be decompressed is returned,
      with :attr:`CidContent.complete` set to :obj:`False`. If none could be
      decompressed, :class:`zlib.error` is raised.
    - :class:`str` data (e.g. a file read with ``FILE SHOW`` over Telnet) is
      used if it's XML (encoded as UTF-8, with a byte order mark if the XML
      declaration names another encoding, so :func:`decode_xml` returns the
      same text), otherwise it's converted back to bytes with Latin-1.
      A compressed file that was transferred as terminal text is usually
      corrupted, so it should be downloaded with FTP or YMODEM instead.

    Args:
        data: Contents of the CID file
        limit: Maximum size of the decompressed data
            (default: :data:`MAX_CID_SIZE`)

    Returns:
        The decompressed data, and how it was compressed

    Raises:
        ValueError: The data decompresses to more than ``limit`` bytes (probably
            a decompression bomb), or it isn't compressed or XML
        zlib.error: The compressed data is invalid, or nothing could be decompressed
    """
    if limit is None:
        limit = MAX_CID_SIZE

    if isinstance(data, str):
        if looks_like_xml(data):
            return CidContent(data=_encode_xml_text(data), compressed=False)
        try:
            data = data.encode("latin-1")
        except UnicodeEncodeError:
            raise ValueError(
                "the data is text that isn't XML or bytes decoded as Latin-1"
            ) from None

    data = bytes(data)

    if not is_zlib_header(data):
        if looks_like_xml(data):
            return CidContent(data=data, compressed=False)
        raise ValueError(f"not zlib-compressed data or XML (starts with {data[:4].hex()})")

    # The DEFLATE data after the zlib header is decompressed by itself (raw), and
    # the Adler-32 checksum after it is checked here. That way, all of the data
    # is kept if only the checksum is wrong, instead of zlib raising an error.
    zo = zlib.decompressobj(-zlib.MAX_WBITS)
    body = data[2:]
    out = bytearray()
    pos = 0
    error = ""

    while pos < len(body) and not zo.eof:
        chunk = body[pos : pos + _CHUNK_SIZE]
        pos += len(chunk)
        try:
            # NOTE: a max_length of 0 means unlimited, this is always at least 1.
            # One more byte than the limit is allowed, so data that's too large
            # is detected without decompressing all of it.
            out += zo.decompress(chunk, limit + 1 - len(out))
        except zlib.error as ex:
            error = str(ex)
            break

        if len(out) > limit:
            raise ValueError(f"the data decompresses to more than {limit} bytes")

    complete = False
    trailing = 0
    if zo.eof:
        tail = zo.unused_data + body[pos:]
        if len(tail) < 4:
            error = "the compressed data is truncated (the checksum is missing)"
        elif int.from_bytes(tail[:4], "big") != zlib.adler32(out):
            error = "the checksum (Adler-32) of the decompressed data is wrong"
            trailing = len(tail) - 4
        else:
            complete = True
            trailing = len(tail) - 4
    elif not error:
        error = "the compressed data is truncated"

    # e.g. only the zlib header, or the data ends in the first DEFLATE block
    if not out and not complete:
        raise zlib.error(f"nothing could be decompressed: {error}")

    return CidContent(
        data=bytes(out),
        compressed=True,
        zlib_header=data[:2].hex().upper(),
        trailing_bytes=trailing,
        complete=complete,
        error=error,
    )


def read_zlib_prefix(stream: BinaryIO, limit: int | None = None) -> bytes:
    """
    Decompress the start of zlib-compressed data from a stream, e.g. to check
    if a file is a CID file. Nothing is decompressed if the stream doesn't
    start with a zlib header, and at most ``limit`` bytes are decompressed.

    Args:
        stream: Binary stream, e.g. an open file
        limit: Maximum size of the data to decompress
            (default: :data:`MAX_CID_CHECK_SIZE`)

    Returns:
        The decompressed data, or empty bytes if the stream isn't zlib data
    """
    if limit is None:
        limit = MAX_CID_CHECK_SIZE

    data = stream.read(2)
    if not is_zlib_header(data):
        return b""

    zo = zlib.decompressobj()
    out = bytearray()

    try:
        while len(out) < limit and not zo.eof:
            if not data:
                data = stream.read(_CHUNK_SIZE)
                if not data:
                    break
            out += zo.decompress(data, limit - len(out))
            data = zo.unconsumed_tail
    except zlib.error as ex:
        log.trace(f"Invalid zlib data after {len(out)} bytes: {ex}")

    return bytes(out)


def has_dtd(data: bytes | str) -> bool:
    """
    If XML has a document type or entity declaration (``<!DOCTYPE``
    or ``<!ENTITY``), which :func:`parse_scl` doesn't allow.
    :class:`bytes` are decoded with :func:`decode_xml`.
    """
    if isinstance(data, (bytes, bytearray, memoryview)):
        data = decode_xml(bytes(data))
    return bool(_DTD_RE.search(data))


class _NoDtdTreeBuilder(ET.TreeBuilder):
    """
    Refuses document type declarations, in case one gets past the text check
    in :func:`parse_scl`. The parser calls this at the start of the declaration.
    """

    def doctype(self, name: str, _pubid: str, _system: str) -> None:
        raise ValueError(f"XML document type declarations aren't allowed ({name})")


def _parse_xml(text: str) -> ET.Element:
    if has_dtd(text):
        raise ValueError(
            "the XML has a document type or entity declaration, which SCL files don't "
            "use, so it wasn't parsed"
        )

    parser = ET.XMLParser(target=_NoDtdTreeBuilder())
    parser.feed(text)
    return parser.close()


def _local(tag: Any) -> str:
    """
    Name of an element in the SCL namespace (or without a namespace),
    or an empty string for elements in other namespaces (e.g. private data).
    """
    if not isinstance(tag, str):
        return ""

    namespace, _, name = tag.rpartition("}")
    if namespace and namespace[1:] != SCL_NAMESPACE:
        return ""

    return name


def _children(elem: ET.Element | None, name: str) -> list[ET.Element]:
    if elem is None:
        return []
    return [child for child in elem if _local(child.tag) == name]


def _child(elem: ET.Element | None, name: str) -> ET.Element | None:
    children = _children(elem, name)
    return children[0] if children else None


def _bool(value: str) -> bool | str:
    lowered = value.strip().lower()
    if lowered in ("true", "1"):
        return True
    if lowered in ("false", "0"):
        return False
    return value


def _attrs(elem: ET.Element | None, names: dict[str, str], bools: tuple = ()) -> dict:
    """
    Attributes of an element that are set and not empty, keyed by the names
    in ``names`` (SCL attribute name: key). Attributes in ``bools`` are
    converted to :class:`bool`.
    """
    values = {}
    if elem is None:
        return values

    for attr, key in names.items():
        value = elem.get(attr)
        if value is None or not value.strip():
            continue
        values[key] = _bool(value) if attr in bools else value.strip()

    return values


def _address_key(p_type: str) -> str:
    """``IP-SUBNET`` => ``ip_subnet``, ``MAC-Address`` => ``mac_address``"""
    return re.sub(r"[^a-z0-9]+", "_", p_type.strip().lower()).strip("_")


def _parse_address(addr: ET.Element | None) -> dict[str, str]:
    """
    ``<P type="...">`` values of an ``Address`` element, e.g.
    ``{"ip": "192.0.2.50", "ip_subnet": "255.255.255.0"}``.
    MAC addresses are formatted like other MAC addresses in PEAT
    (``01:0C:CD:01:00:01``).
    """
    values = {}

    for p in _children(addr, "P"):
        p_type = _address_key(p.get("type", ""))
        value = (p.text or "").strip()
        if not p_type or not value or p_type in values:
            continue
        values[p_type] = clean_mac(value) if p_type == "mac_address" else value

    return values


def _time_ms(elem: ET.Element | None) -> int | float | None:
    """
    Duration of a ``MinTime`` or ``MaxTime`` element in milliseconds. The SCL
    schema defines these in milliseconds (``unit="s"``, ``multiplier="m"``).
    """
    if elem is None or not (elem.text or "").strip():
        return None

    multiplier = _MS_MULTIPLIERS.get(elem.get("multiplier", "m").strip())
    if elem.get("unit", "s").strip() != "s" or multiplier is None:
        return None

    try:
        value = float(elem.text.strip()) * multiplier
    except ValueError:
        return None

    return int(value) if value.is_integer() else value


def _parse_header(root: ET.Element) -> dict:
    header_elem = _child(root, "Header")
    header = _attrs(
        header_elem,
        {
            "id": "id",
            "version": "version",
            "revision": "revision",
            "toolID": "tool_id",
            "nameStructure": "name_structure",
        },
    )

    hitems = [
        item for hist in _children(header_elem, "History") for item in _children(hist, "Hitem")
    ]
    if hitems:
        header["history_count"] = len(hitems)
        last = _attrs(
            hitems[-1],
            {
                "version": "version",
                "revision": "revision",
                "when": "when",
                "who": "who",
                "what": "what",
                "why": "why",
            },
        )
        if last:
            header["last_history"] = last

    return header


def _parse_ied(ied_elem: ET.Element) -> dict:
    ied = _attrs(
        ied_elem,
        {
            "name": "name",
            "desc": "desc",
            "type": "type",
            "manufacturer": "manufacturer",
            "configVersion": "config_version",
            "originalSclVersion": "original_scl_version",
            "originalSclRevision": "original_scl_revision",
        },
    )

    services = _child(ied_elem, "Services")
    if services is not None:
        ied["services"] = sorted({_local(s.tag) for s in services if _local(s.tag)})

    counts = {
        "access_point": 0,
        "ldevice": 0,
        "ln": 0,
        "dataset": 0,
        "report_control": 0,
        "log_control": 0,
        "gse_control": 0,
        "smv_control": 0,
        "ext_ref": 0,
    }
    access_points = []
    ldevices = []
    gse_controls = []
    smv_controls = []
    ln_classes = set()
    input_ieds = set()

    for ap_elem in _children(ied_elem, "AccessPoint"):
        counts["access_point"] += 1
        ap = _attrs(
            ap_elem,
            {"name": "name", "desc": "desc", "router": "router", "clock": "clock"},
            bools=("router", "clock"),
        )

        server_at = _child(ap_elem, "ServerAt")
        if server_at is not None and server_at.get("apName"):
            ap["server_at"] = server_at.get("apName").strip()

        server = _child(ap_elem, "Server")
        ap["has_server"] = server is not None

        auth = _attrs(
            _child(server, "Authentication"),
            {x: x for x in ("none", "password", "weak", "strong", "certificate")},
            bools=("none", "password", "weak", "strong", "certificate"),
        )
        if auth:
            ap["authentication"] = auth

        ap_ldevices = []
        for ld_elem in _children(server, "LDevice"):
            ld = _attrs(ld_elem, {"inst": "inst", "ldName": "ld_name", "desc": "desc"})
            ld_inst = ld.get("inst", "")
            if ap.get("name"):
                ld["access_point"] = ap["name"]

            lns = _children(ld_elem, "LN0") + _children(ld_elem, "LN")
            ld["ln_count"] = len(lns)
            counts["ln"] += len(lns)

            for ln in lns:
                if ln.get("lnClass", "").strip():
                    ln_classes.add(ln.get("lnClass").strip())

                counts["dataset"] += len(_children(ln, "DataSet"))
                counts["report_control"] += len(_children(ln, "ReportControl"))
                counts["log_control"] += len(_children(ln, "LogControl"))

                for gse_elem in _children(ln, "GSEControl"):
                    gse_ctl = {"ld_inst": ld_inst}
                    gse_ctl.update(
                        _attrs(
                            gse_elem,
                            {
                                "name": "name",
                                "datSet": "dataset",
                                "appID": "go_id",
                                "confRev": "conf_rev",
                                "type": "type",
                                "securityEnable": "security_enable",
                            },
                        )
                    )
                    gse_controls.append(gse_ctl)

                for smv_elem in _children(ln, "SampledValueControl"):
                    smv_ctl = {"ld_inst": ld_inst}
                    smv_ctl.update(
                        _attrs(
                            smv_elem,
                            {
                                "name": "name",
                                "datSet": "dataset",
                                "smvID": "smv_id",
                                "confRev": "conf_rev",
                                "smpRate": "smp_rate",
                                "nofASDU": "nof_asdu",
                                "multicast": "multicast",
                                "securityEnable": "security_enable",
                            },
                            bools=("multicast",),
                        )
                    )
                    smv_controls.append(smv_ctl)

                for inputs in _children(ln, "Inputs"):
                    for ext_ref in _children(inputs, "ExtRef"):
                        counts["ext_ref"] += 1
                        if ext_ref.get("iedName", "").strip():
                            input_ieds.add(ext_ref.get("iedName").strip())

            ldevices.append(ld)
            if ld_inst:
                ap_ldevices.append(ld_inst)

        if ap_ldevices:
            ap["ldevices"] = ap_ldevices
        access_points.append(ap)

    counts["ldevice"] = len(ldevices)
    counts["gse_control"] = len(gse_controls)
    counts["smv_control"] = len(smv_controls)

    ied["access_points"] = access_points
    ied["ldevices"] = ldevices
    ied["ln_classes"] = sorted(ln_classes)
    ied["gse_controls"] = gse_controls
    ied["smv_controls"] = smv_controls
    # Other IEDs this IED subscribes to (e.g. GOOSE messages it receives)
    ied["input_ieds"] = sorted(input_ieds - {ied.get("name", "")})
    ied["counts"] = counts

    return ied


def _parse_communication(root: ET.Element) -> list[dict]:
    subnetworks = []

    for comm in _children(root, "Communication"):
        for sn_elem in _children(comm, "SubNetwork"):
            subnetwork = _attrs(sn_elem, {"name": "name", "type": "type", "desc": "desc"})
            connected_aps = []

            for cap_elem in _children(sn_elem, "ConnectedAP"):
                cap = _attrs(
                    cap_elem, {"iedName": "ied_name", "apName": "ap_name", "desc": "desc"}
                )

                address = _parse_address(_child(cap_elem, "Address"))
                if address:
                    cap["address"] = address

                # GOOSE (GSE) and Sampled Values (SMV) multicast addresses
                for kind in ("GSE", "SMV"):
                    entries = []
                    for elem in _children(cap_elem, kind):
                        entry = _attrs(elem, {"ldInst": "ld_inst", "cbName": "cb_name"})
                        entry.update(_parse_address(_child(elem, "Address")))
                        for time_tag, key in (
                            ("MinTime", "min_time_ms"),
                            ("MaxTime", "max_time_ms"),
                        ):
                            value = _time_ms(_child(elem, time_tag))
                            if value is not None:
                                entry[key] = value
                        entries.append(entry)

                    if entries:
                        cap[kind.lower()] = entries

                connected_aps.append(cap)

            subnetwork["connected_aps"] = connected_aps
            subnetworks.append(subnetwork)

    return subnetworks


def parse_scl(data: bytes | str) -> dict:
    """
    Parse a SCL file (IEC 61850-6), e.g. the decompressed contents of
    ``SET_61850.CID``. The elements are matched in the SCL namespace or
    without a namespace, and elements in other namespaces (private data) are
    ignored. Refer to the warning in :mod:`~peat.modules.sel.sel_scl` about
    untrusted XML.

    Keys in the result (keys are left out if the file doesn't have the value):

    - ``scl_version``, ``scl_revision``, ``scl_release``: the edition of the
      SCL schema, e.g. ``2007``, ``B``, ``4``
    - ``header``: ``id``, ``version``, ``revision``, ``tool_id``,
      ``name_structure``, ``history_count``, and ``last_history`` (the
      last ``Hitem``: ``version``, ``revision``, ``when``, ``who``, ``what``, ``why``)
    - ``ieds``: a dict for each ``IED``:

      - ``name``, ``desc``, ``type``, ``manufacturer``, ``config_version``,
        ``original_scl_version``, ``original_scl_revision``
      - ``services``: names of the elements in ``Services`` (the services the IED supports)
      - ``access_points``: ``name``, ``desc``, ``router``, ``clock``,
        ``has_server``, ``server_at``, ``authentication`` (the MMS server's
        ``Authentication`` flags, e.g. ``{"none": True}``), and ``ldevices``
      - ``ldevices``: ``inst``, ``ld_name``, ``desc``, ``access_point``, ``ln_count``
      - ``ln_classes``: the logical node classes used (e.g. ``PTOC``, ``XCBR``)
      - ``gse_controls``: GOOSE control blocks (``ld_inst``, ``name``,
        ``dataset``, ``go_id``, ``conf_rev``, ``type``, ``security_enable``)
      - ``smv_controls``: Sampled Value control blocks
      - ``input_ieds``: other IEDs in the ``ExtRef`` inputs, e.g. the
        IEDs whose GOOSE messages this IED subscribes to
      - ``counts``: number of access points, logical devices (``ldevice``),
        logical nodes (``ln``), data sets, report, log, GOOSE, and Sampled
        Value control blocks, and ``ExtRef`` inputs

    - ``subnetworks``: ``name``, ``type``, ``desc``, and ``connected_aps``:
      ``ied_name``, ``ap_name``, ``desc``, ``address`` (the ``P`` values, e.g.
      ``ip``, ``ip_subnet``, ``ip_gateway``, ``osi_ap_title``), and ``gse``
      and ``smv`` (``ld_inst``, ``cb_name``, ``mac_address``, ``appid``,
      ``vlan_id``, ``vlan_priority``, ``min_time_ms``, ``max_time_ms``)

    Args:
        data: The SCL XML. :class:`bytes` are decoded with :func:`decode_xml`.

    Returns:
        The values from the SCL

    Raises:
        ValueError: The XML has a document type or entity declaration,
            or the root element isn't ``SCL``
        xml.etree.ElementTree.ParseError: The XML is invalid
    """
    if isinstance(data, (bytes, bytearray, memoryview)):
        data = decode_xml(bytes(data))

    root = _parse_xml(data)
    if _local(root.tag) != "SCL":
        raise ValueError(f"the root element is '{root.tag}', not 'SCL'")

    info = _attrs(
        root,
        {"version": "scl_version", "revision": "scl_revision", "release": "scl_release"},
    )
    info["header"] = _parse_header(root)
    info["ieds"] = [_parse_ied(ied) for ied in _children(root, "IED")]
    info["subnetworks"] = _parse_communication(root)

    return info


def is_sel_ied(ied: dict) -> bool:
    """
    If an IED from :func:`parse_scl` is a SEL device: its manufacturer is
    SEL (or not set), or its type starts with ``SEL``.
    """
    manufacturer = ied.get("manufacturer", "").strip().lower()
    return (
        not manufacturer
        or manufacturer == "sel"
        or "schweitzer" in manufacturer
        or ied.get("type", "").upper().startswith("SEL")
    )


def select_ied(scl: dict, ied_name: str = "") -> dict | None:
    """
    The IED in a parsed SCL file that's the device: the IED named ``ied_name``
    (e.g. from the ``ID`` command), or if there's only one IED (as in a CID
    file), that IED, or the first SEL IED.

    Args:
        scl: Output of :func:`parse_scl`
        ied_name: Name of the device's IED, if it's known

    Returns:
        The IED, or :obj:`None` if the file doesn't have any IEDs
    """
    ieds = scl.get("ieds") or []
    if not ieds:
        return None

    if ied_name:
        for ied in ieds:
            if ied.get("name") == ied_name:
                return ied

    if len(ieds) == 1:
        return ieds[0]

    for ied in ieds:
        if is_sel_ied(ied):
            return ied

    return ieds[0]


def _check_mismatches(iec: dict) -> None:
    """
    Compare the values from the ``ID`` command with the IED in the SCL, and
    warn about (and record) the values that differ. The relay reports the
    values of the CID file it's using, so a difference means the SCL that
    was parsed isn't the configuration the relay is running (e.g. a CID
    file that the relay rejected, or a file from another relay).
    """
    from_id = iec.get("id_command") or {}
    scl_ied = (iec.get("scl") or {}).get("ied") or {}

    mismatches = {}
    for key, scl_key in _COMPARED:
        id_value = from_id.get(key)
        scl_value = scl_ied.get(scl_key)
        if id_value and scl_value and id_value != scl_value:
            mismatches[key] = {"id_command": id_value, "scl": scl_value}

    previous = iec.get("mismatches") or {}
    for key, values in mismatches.items():
        if previous.get(key) != values:
            log.warning(
                f"The IEC 61850 {key} reported by the relay's 'id' command "
                f"('{values['id_command']}') is different from the {key} in the "
                f"SCL file ('{values['scl']}')"
            )

    if mismatches:
        iec["mismatches"] = mismatches
    else:
        iec.pop("mismatches", None)


def _add_related_ip(dev: DeviceData, value: str) -> None:
    try:
        ip = validate_ip(value)
    except ValueError:
        log.debug(f"Invalid IP address in SCL for {dev.get_id()}: {value!r}")
        return

    if ip and ip not in ("0.0.0.0", "::"):
        dev.related.ip.add(ip)


def _add_related_mac(dev: DeviceData, value: str) -> None:
    try:
        mac = validate_mac(value)
    except ValueError:
        log.debug(f"Invalid MAC address in SCL for {dev.get_id()}: {value!r}")
        return

    if mac:
        dev.related.mac.add(mac)


def _mms_port(address: dict) -> int:
    """
    The MMS port: the ``MMS-Port`` address, if the SCL has one
    (IEC 61850-6 Edition 2.1), or the standard port.
    """
    try:
        port = int(address.get("mms_port", MMS_PORT))
    except ValueError:
        return MMS_PORT
    return port if 0 < port <= 65535 else MMS_PORT


def _iec_extra(dev: DeviceData) -> dict:
    if not isinstance(dev.extra.get(EXTRA_KEY), dict):
        dev.extra[EXTRA_KEY] = {}
    return dev.extra[EXTRA_KEY]


def _store_scl_summary(iec: dict, summary: dict, dev: DeviceData) -> bool:
    """
    Store the summary of an SCL file in ``iec["scl"]``, or in
    ``iec["other_scl_files"]`` if the device already has the summary of
    another file. The first file with an IED is kept in ``scl``. A summary
    of the same file (the same ``file`` name) replaces the previous one.

    Returns:
        If the summary is in ``scl`` (the file the IEC 61850 values are from)
    """
    current = iec.get("scl")
    name = summary.get("file", "")
    others = [s for s in iec.get("other_scl_files", []) if s.get("file", "") != name]

    is_main = (
        not current
        or current.get("file", "") == name
        or (bool(summary.get("ied")) and not current.get("ied"))
    )

    if is_main:
        if current and current.get("file", "") != name:
            others.append(current)
        iec["scl"] = summary
    else:
        others.append(summary)

    if others:
        iec["other_scl_files"] = others
        log.warning(
            f"{dev.get_id()} has more than one SCL file: the IEC 61850 values are "
            f"from '{iec['scl'].get('file', '')}', and the summaries of the other "
            f"files are in extra.iec61850.other_scl_files "
            f"({', '.join(repr(s.get('file', '')) for s in others)})"
        )
    else:
        iec.pop("other_scl_files", None)

    return is_main


def process_scl_into_dev(scl: dict, dev: DeviceData, source: str = "") -> dict | None:
    """
    Put the values from a parsed SCL file into the device data model.

    - ``dev.extra["iec61850"]["scl"]`` is a summary of the file: ``file``
      (``source``), ``scl_version``, ``scl_revision``, ``scl_release``,
      ``header``, ``ied`` (the device's IED, refer to :func:`select_ied`),
      ``connected_aps`` (the device's network addresses and GOOSE and
      Sampled Value addresses, with the ``subnetwork`` they're on), ``peers``
      (addresses of the other IEDs in the file), ``other_ieds``, and ``ied_count``.
    - ``ied_name``, ``ied_type``, ``config_version``, and ``manufacturer`` in
      ``dev.extra["iec61850"]`` are set from the IED, unless the ``ID``
      command already set them. A warning is logged for values that are
      different from the ``ID`` command (refer to ``mismatches``).
    - An ``iec61850`` service (MMS, TCP port 102) is added if the IED has an
      MMS server, with the IED name and access point in its ``extra``. It's
      added to the interface with the IP address in the SCL, if the device
      has an interface with that IP.
    - IP addresses (including gateways) and GOOSE and Sampled Value MAC
      addresses are added to ``dev.related``, and ``iec61850`` to
      ``dev.related.protocols``.
    - If the device doesn't have a name, the IED name is used.

    If the device already has the summary of another SCL file (e.g. a
    directory with more than one ``.CID`` file), the first file with an IED
    is used for the values above, the summaries of the other files are in
    ``dev.extra["iec61850"]["other_scl_files"]``, and a warning is logged.
    Only their addresses are added to ``dev.related``.

    Args:
        scl: Output of :func:`parse_scl`
        dev: The device
        source: Name of the file the SCL is from, e.g. ``SET_61850.CID``

    Returns:
        The IED that was used, or :obj:`None` if the file has no IEDs
    """
    iec = _iec_extra(dev)
    id_ied_name = (iec.get("id_command") or {}).get("ied_name", "")

    summary = {"file": source} if source else {}
    for key in ("scl_version", "scl_revision", "scl_release"):
        if scl.get(key):
            summary[key] = scl[key]
    summary["header"] = scl.get("header", {})
    summary["ied_count"] = len(scl.get("ieds", []))

    ied = select_ied(scl, id_ied_name)
    if ied is None:
        log.warning(f"No IED in the SCL{f' in {source}' if source else ''} for {dev.get_id()}")
        _store_scl_summary(iec, summary, dev)
        return None

    ied_name = ied.get("name", "")
    if summary["ied_count"] > 1:
        log.info(
            f"{summary['ied_count']} IEDs in the SCL{f' in {source}' if source else ''}, "
            f"using '{ied_name}' for {dev.get_id()}"
        )

    own_aps = []
    peers = []
    for subnetwork in scl.get("subnetworks", []):
        for cap in subnetwork.get("connected_aps", []):
            entry = dict(cap)
            if subnetwork.get("name"):
                entry["subnetwork"] = subnetwork["name"]
            if ied_name and cap.get("ied_name") == ied_name:
                own_aps.append(entry)
            else:
                peers.append(entry)

    summary["ied"] = ied
    summary["connected_aps"] = own_aps
    summary["peers"] = peers
    summary["other_ieds"] = [
        other.get("name", "") for other in scl.get("ieds", []) if other is not ied
    ]
    is_main = _store_scl_summary(iec, summary, dev)

    if is_main:
        for key, scl_key in (
            ("ied_name", "name"),
            ("ied_type", "type"),
            ("config_version", "config_version"),
            ("manufacturer", "manufacturer"),
        ):
            if ied.get(scl_key) and not iec.get(key):
                iec[key] = ied[scl_key]

        _check_mismatches(iec)

    # Addresses of this IED and its peers (e.g. the IEDs it exchanges GOOSE with)
    for cap in own_aps + peers:
        address = cap.get("address", {})
        for key in ("ip", "ip_gateway", "ipv6", "ipv6_gateway"):
            if address.get(key):
                _add_related_ip(dev, address[key])
        for entry in cap.get("gse", []) + cap.get("smv", []):
            if entry.get("mac_address"):
                _add_related_mac(dev, entry["mac_address"])

    dev.related.protocols.add("iec61850")

    if not is_main:
        return ied

    # MMS server, on the access point with a server (usually "S1" on SEL relays)
    server_aps = [ap for ap in ied.get("access_points", []) if ap.get("has_server")]
    if server_aps:
        ap_name = server_aps[0].get("name", "")
        address = next((c.get("address", {}) for c in own_aps if c.get("ap_name") == ap_name), {})
        ip = address.get("ip", "")

        svc_extra = {"ied_name": ied_name} if ied_name else {}
        if ap_name:
            svc_extra["access_point"] = ap_name

        svc = Service(
            protocol="iec61850",
            port=_mms_port(address),
            transport="tcp",
            extra=svc_extra,
        )

        if ip and any(iface.ip == ip for iface in dev.interface):
            dev.store("service", svc, interface_lookup={"ip": ip})
        else:
            dev.store("service", svc)

        if ip and dev.ip and ip != dev.ip:
            log.info(
                f"The IP address of IED '{ied_name}' in the SCL ({ip}) "
                f"is different from the IP address of {dev.get_id()} ({dev.ip})"
            )

    if not dev.name and ied_name:
        dev.name = ied_name

    return ied


def process_id_info(info: dict, dev: DeviceData) -> None:
    """
    Put the IEC 61850 values from the ``ID`` command output (from
    :func:`~peat.modules.sel.sel_cascii.parse_id_output`) into
    ``dev.extra["iec61850"]``, and add an ``iec61850`` service (MMS, TCP
    port 102) if the relay reports an IED name.

    ``iec61850_parse_failure`` is removed from ``info`` (it's
    ``dev.extra["iec61850"]["parse_failure"]``). ``iedName``, ``type``,
    ``configVersion``, and ``LIB61850ID`` are left in ``info``, so
    :func:`~peat.modules.sel.relay_parse.process_info_into_dev` still adds
    them to the top level of ``dev.extra``, as before. Nothing is done if
    ``info`` doesn't have any of these values (e.g. it's from another
    command), and ``type`` is only used if ``info`` has one of the other values.

    Args:
        info: Values from the ``ID`` command. ``iec61850_parse_failure``
            is removed from it.
        dev: The device
    """
    failures = info.pop("iec61850_parse_failure", None)
    if not failures and not any(key in info for key in ID_KEYS if key != "type"):
        return

    iec = _iec_extra(dev)
    if failures:
        iec["parse_failure"] = list(failures)
    else:
        iec.pop("parse_failure", None)

    values = {}
    for id_key, key in ID_KEYS.items():
        value = info.get(id_key)
        if isinstance(value, str) and value.strip() and value.strip().upper() != PARSE_FAILURE:
            values[key] = value.strip()

    if not values:
        return

    iec.setdefault("id_command", {}).update(values)
    # The relay reports the configuration it's running, use it instead of the SCL
    iec.update(values)
    _check_mismatches(iec)

    if values.get("ied_name"):
        dev.store(
            "service",
            Service(
                protocol="iec61850",
                port=MMS_PORT,
                transport="tcp",
                extra={"ied_name": values["ied_name"]},
            ),
        )


